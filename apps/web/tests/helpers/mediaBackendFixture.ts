import { readFile } from 'node:fs/promises';
import type { Page } from '@playwright/test';
import type { DirectoryUser } from '@upperroom/shared/types/User';
import { installMediaProviderStatusFixture } from './providerStatusFixture';

const ORIGIN = 'http://127.0.0.1:3004';
const PROJECT = 'demo-temporal-ci';
export const MEDIA_BUNDLE_QUERIES = {
  createtopicbundle: 'latest-topics-query',
  createsubtitlebundle: 'latest-subtitles-query',
  createbiblechapterbundle: 'latest-bible-chapters-query',
  createsundayhomilybundle: 'latest-sunday-homilies-query',
  createholyweekbundle: 'latest-holy-week-query',
  createlatestlistbundle: 'latest-list-query',
} as const;
interface Fixture {
  schemaVersion: 1;
  projectId: typeof PROJECT;
  bundles: Record<string, { namedQuery: string; bodyBase64: string; timestamp: number }>;
  users: DirectoryUser[];
}
/** Transport validation only. Firebase's real loadBundle/namedQuery validates the Admin-generated bytes. */
export function parseMediaBackendFixture(value: unknown): Fixture {
  const fixture = value as Fixture;
  if (
    !fixture ||
    fixture.schemaVersion !== 1 ||
    fixture.projectId !== PROJECT ||
    !fixture.bundles ||
    Object.keys(fixture.bundles).sort().join(',') !== Object.keys(MEDIA_BUNDLE_QUERIES).sort().join(',')
  )
    throw new Error('Invalid demo bundle fixture inventory');
  for (const [name, query] of Object.entries(MEDIA_BUNDLE_QUERIES)) {
    const item = fixture.bundles[name];
    if (
      !item ||
      item.namedQuery !== query ||
      !Number.isSafeInteger(item.timestamp) ||
      item.timestamp <= 0 ||
      typeof item.bodyBase64 !== 'string'
    )
      throw new Error('Invalid demo bundle fixture metadata');
    const bytes = Buffer.from(item.bodyBase64, 'base64');
    if (!bytes.length || bytes.length > 1024 * 1024 || bytes.toString('base64') !== item.bodyBase64)
      throw new Error('Invalid bounded demo bundle encoding');
  }
  const user = fixture.users?.[0];
  const allowedKeys = [
    'uid',
    'email',
    'photoURL',
    'displayName',
    'role',
    'firstName',
    'lastName',
    'emailVerified',
    'isAnonymous',
    'metadata',
    'providerData',
    'refreshToken',
    'tenantId',
    'phoneNumber',
    'providerId',
  ];
  if (
    !Array.isArray(fixture.users) ||
    fixture.users.length !== 1 ||
    !user ||
    user.uid !== 'playwright-e2e' ||
    user.email !== 'syntheticmedia-uploader@example.test' ||
    user.role !== 'uploader' ||
    user.refreshToken !== '' ||
    user.photoURL !== null ||
    user.phoneNumber !== null ||
    user.tenantId !== null ||
    !Array.isArray(user.providerData) ||
    user.providerData.length ||
    Object.keys(user).some((key) => !allowedKeys.includes(key))
  )
    throw new Error('Invalid synthetic uploader directory fixture');
  return fixture;
}

/** Only isolated media tests replace these exact read endpoints; no Functions emulator is started. */
export async function installMediaBackendFixtures(page: Page): Promise<void> {
  await installMediaProviderStatusFixture(page);
  if (process.env.URM_MEDIA_BROWSER_STATUS_FIXTURE === undefined) return;
  if (
    process.env.URM_MEDIA_BROWSER_STATUS_FIXTURE !== 'true' ||
    process.env.GCLOUD_PROJECT !== PROJECT ||
    process.env.PLAYWRIGHT_BASE_URL !== ORIGIN
  )
    throw new Error('Media backend fixtures require the isolated demo harness');
  const file = process.env.URM_MEDIA_BROWSER_BUNDLE_FIXTURES_FILE;
  if (!file || !file.startsWith('/')) throw new Error('An actual demo fixture file is required');
  const raw = await readFile(file);
  if (raw.length > 8 * 1024 * 1024) throw new Error('Demo fixture exceeds its transport budget');
  const fixture = parseMediaBackendFixture(JSON.parse(raw.toString('utf8')));
  for (const [name, item] of Object.entries(fixture.bundles)) {
    // This is the current BundleManager emulator URL, not the callable SDK's dedicated port.
    const endpoint = `http://127.0.0.1:5001/${PROJECT}/us-central1/${name}`;
    await page.route(
      (url) => url.href === endpoint,
      async (route) => {
        const request = route.request();
        if (request.headers().origin !== ORIGIN) throw new Error('Unexpected demo bundle origin');
        if (request.method() === 'OPTIONS') {
          if (request.headers()['access-control-request-method'] !== 'GET')
            throw new Error('Unexpected demo bundle preflight');
          await route.fulfill({
            status: 204,
            headers: {
              'access-control-allow-origin': ORIGIN,
              'access-control-allow-methods': 'GET',
              'access-control-allow-headers': 'accept, cache-control, pragma',
              vary: 'Origin',
            },
          });
          return;
        }
        if (request.method() !== 'GET') throw new Error('Unexpected demo bundle request');
        await route.fulfill({
          status: 200,
          contentType: 'application/octet-stream',
          body: Buffer.from(item.bodyBase64, 'base64'),
          headers: {
            'access-control-allow-origin': ORIGIN,
            'access-control-expose-headers': 'X-Bundle-Timestamp, X-Bundle-Source',
            'X-Bundle-Timestamp': String(item.timestamp),
            'X-Bundle-Source': 'demo-admin-sdk-fixture',
            vary: 'Origin',
          },
        });
      }
    );
  }
  const port = process.env.NEXT_PUBLIC_FIREBASE_FUNCTIONS_EMULATOR_PORT;
  if (!port || !/^[1-9]\d{0,4}$/.test(port) || Number(port) > 65535) throw new Error('Invalid demo callable port');
  const endpoint = `http://127.0.0.1:${port}/${PROJECT}/us-central1/getusersbyids`;
  await page.route(
    (url) => url.href === endpoint,
    async (route) => {
      const request = route.request();
      if (request.headers().origin !== ORIGIN) throw new Error('Unexpected demo directory origin');
      const headers = {
        'access-control-allow-origin': ORIGIN,
        'access-control-allow-methods': 'POST',
        'access-control-allow-headers': 'authorization, content-type, x-firebase-appcheck, firebase-instance-id-token',
        vary: 'Origin',
      };
      if (request.method() === 'OPTIONS') {
        if (request.headers()['access-control-request-method'] !== 'POST')
          throw new Error('Unexpected demo directory preflight');
        await route.fulfill({ status: 204, headers });
        return;
      }
      if (request.method() !== 'POST' || !/^Bearer .+/.test(request.headers().authorization ?? ''))
        throw new Error('Authenticated demo directory request required');
      const body = request.postDataJSON() as { data?: { uids?: unknown } };
      const uids = body?.data?.uids;
      if (
        Object.keys(body ?? {}).join(',') !== 'data' ||
        Object.keys(body.data ?? {}).join(',') !== 'uids' ||
        !Array.isArray(uids) ||
        uids.length > 100 ||
        uids.some((uid) => uid !== 'playwright-e2e')
      )
        throw new Error('Unexpected demo uploader lookup');
      await route.fulfill({
        status: 200,
        headers,
        json: { result: { status: 'success', data: fixture.users.filter((user) => uids.includes(user.uid)) } },
      });
    }
  );
}
